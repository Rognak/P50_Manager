import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import icons from 'simple-icons/icons.json' with { type: 'json' }

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const csvPath = path.resolve(root, '../backend/data/technologies.csv')
const outputPath = path.resolve(root, 'src/lib/technology-icons.generated.ts')
const backendMapPath = path.resolve(root, '../backend/data/technology_icon_map.csv')

function parseCsvLine(line) {
  const values = []
  let value = ''
  let quoted = false
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index]
    if (char === '"') {
      if (quoted && line[index + 1] === '"') {
        value += '"'
        index += 1
      } else {
        quoted = !quoted
      }
    } else if (char === ',' && !quoted) {
      values.push(value)
      value = ''
    } else {
      value += char
    }
  }
  values.push(value)
  return values
}

const lines = fs.readFileSync(csvPath, 'utf8').trim().split(/\r?\n/)
const headers = parseCsvLine(lines[0])
const technologies = lines.slice(1).map((line) => {
  const values = parseCsvLine(line)
  return Object.fromEntries(headers.map((header, index) => [header, values[index] || '']))
})
const normalize = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, '')
const iconIndex = new Map()
for (const icon of icons) {
  const aliases = [
    ...(icon.aliases?.aka || []),
    ...(icon.aliases?.dup || []).map((item) => item.title),
  ]
  for (const value of [icon.title, icon.slug, ...aliases]) {
    if (value) iconIndex.set(normalize(value), icon)
  }
}

const overrides = {
  bash: 'shell',
  csharp: 'sharp',
  kafka: 'apachekafka',
  'material-ui': 'mui',
  'next-js': 'nextdotjs',
  openshift: 'redhatopenshift',
  reactjs: 'react',
  rxjs: 'reactivex',
  'tailwind-css': 'tailwindcss',
  'tanstack-query': 'reactquery',
  'vue-js': 'vuedotjs',
}

const selectedBySlug = new Map()
const aliasesByName = new Map()
const technologyIconRows = []
for (const technology of technologies) {
  let icon = icons.find((item) => item.slug === overrides[technology.technology_id])
  const candidates = [
    technology.name,
    technology.technology_id,
    ...technology.aliases.split('|'),
  ]
  for (const candidate of candidates) {
    if (icon) break
    icon = iconIndex.get(normalize(candidate))
  }
  if (icon) {
    selectedBySlug.set(icon.slug, icon)
    technologyIconRows.push({
      technology_id: technology.technology_id,
      name: technology.name,
      aliases: technology.aliases,
      icon_slug: icon.slug,
    })
    for (const candidate of candidates) {
      if (candidate) aliasesByName.set(normalize(candidate), icon.slug)
    }
  }
}

for (const slug of [
  'apachekafka', 'delphi', 'docker', 'fastapi', 'flask', 'kubernetes',
  'postgresql', 'python', 'react', 'redis', 'redhatopenshift', 'sharp', 'typescript',
]) {
  const icon = icons.find((item) => item.slug === slug)
  if (icon) selectedBySlug.set(slug, icon)
}
for (const [name, slug] of Object.entries({
  'C#': 'sharp',
  Kafka: 'apachekafka',
  OpenShift: 'redhatopenshift',
  ReactJS: 'react',
})) aliasesByName.set(normalize(name), slug)

const selected = [...selectedBySlug.values()].sort((left, right) =>
  left.title.localeCompare(right.title),
)
let output = '// Generated by scripts/generate-technology-icons.mjs. Do not edit manually.\n'
selected.forEach((icon, index) => {
  output += `import icon${index} from 'simple-icons/icons/${icon.slug}.svg?no-inline'\n`
})
output += '\nexport interface TechnologyIconDefinition { slug: string; title: string; hex: string; url: string }\n\n'
output += 'export const TECHNOLOGY_ICON_OPTIONS: TechnologyIconDefinition[] = [\n'
selected.forEach((icon, index) => {
  output += `  { slug: ${JSON.stringify(icon.slug)}, title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(`#${icon.hex}`)}, url: icon${index} },\n`
})
output += ']\n\n'
output += 'export const TECHNOLOGY_ICONS = new Map(TECHNOLOGY_ICON_OPTIONS.map((icon) => [icon.slug, icon]))\n'
output += `export const TECHNOLOGY_ICON_ALIASES: Record<string, string> = ${JSON.stringify(Object.fromEntries([...aliasesByName].sort()), null, 2)}\n`
fs.writeFileSync(outputPath, output)
const quoteCsv = (value) => `"${String(value).replaceAll('"', '""')}"`
const backendMap = [
  'technology_id,name,aliases,icon_slug',
  ...technologyIconRows.map((row) => [row.technology_id, row.name, row.aliases, row.icon_slug].map(quoteCsv).join(',')),
].join('\n') + '\n'
fs.writeFileSync(backendMapPath, backendMap)
console.log(`Generated ${selected.length} icons and ${technologyIconRows.length} mappings`)
