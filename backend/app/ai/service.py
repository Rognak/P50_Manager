def build_employee_context(
    employee: Employee,
    profile_items: list,
    focus_competencies: list[Competency],
) -> str:
    role_name = employee.role.name if employee.role else "—"
    grade_code = employee.grade.code if employee.grade else "—"
    lines = [
        f"Сотрудник: {employee.full_name}",
        f"Должность: {employee.position or '—'}",
        f"Роль: {role_name} / грейд: {grade_code}",
        "",
        "Шкала уровней владения:",
        "  0 — не требуется, 1 — начальный, 2 — базовый,",
        "  3 — продвинутый, 4 — экспертный, 5 — выдающийся",
    ]

    assessed = [
        i for i in profile_items if i.current_level is not None or i.required_level is not None
    ]
    if assessed:
        lines.append("")
        lines.append("Текущий профиль МПК (компетенция — текущий / требуемый / гэп):")
        for item in assessed[:30]:
            cur = item.current_level if item.current_level is not None else "—"
            req = item.required_level if item.required_level is not None else "—"
            gap = item.gap if item.gap is not None else "—"
            lines.append(f"  • {item.competency_name}: {cur} / {req} / {gap}")

    if focus_competencies:
        lines.append("")
        lines.append("Компетенции в фокусе (с индикаторами уровня):")
        for c in focus_competencies:
            lines.append(f"  [{c.id}] {c.name}")
            if c.description:
                lines.append(f"      {c.description[:300]}")
            for cr in list(c.criteria)[:8]:
                lines.append(f"        {cr.order_num}. {cr.description[:250]}")

    return "\n".join(lines)


SchemaT = TypeVar("SchemaT", bound=BaseModel)


async def _json_call(client: AsyncOpenAI, prompt: str, schema: type[SchemaT]) -> SchemaT:
    try:
        resp = await client.chat.completions.create(
            model=model_of(client),
            messages=[
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": prompt},
            ],
            response_format={"type": "json_object"},
            temperature=0.5,
            max_tokens=20000,
        )
    except OpenAIError as e:
        raise HTTPException(status_code=502, detail=f"Ошибка AI-провайдера: {e}")

    content = (resp.choices[0].message.content or "").strip()
    # DeepSeek иногда оборачивает ответ в ```json ... ``` — снимем
    if content.startswith("```"):
        content = content.strip("`").lstrip("json").strip()

    try:
        data = json.loads(content)
    except json.JSONDecodeError:
        print(content)
        raise HTTPException(status_code=502, detail="AI вернул невалидный JSON")

    try:
        return schema.model_validate(data)
    except ValidationError as e:
        raise HTTPException(status_code=502, detail=f"AI вернул данные не по схеме: {e}")


async def generate_questions(
    client: AsyncOpenAI,
    context: str,
    params: AIGenParams,
) -> AIQuestionsResult:
    diff = _DIFF_DESC[params.difficulty]
    if params.difficulty == "custom" and params.custom_level is not None:
        diff = f"фиксированный уровень {params.custom_level}"
    prompt = (
        f"{context}\n\n"
        "Условия генерации вопросов:\n"
        f"- количество: {params.count}\n"
        f"- тип: {_TYPE_DESC[params.type]}\n"
        f"- сложность: {diff}\n"
        f"- формат ответа на встрече: {_FMT_DESC[params.format]}\n"
        f"- бюджет времени: ~{params.time_budget_min} мин на вопрос\n"
        f"- дополнительные инструкции: {params.custom_constraints or '—'}\n\n"
        f"Сгенерируй ровно {params.count} вопросов для очной встречи 1:1.\n"
        "Каждый вопрос должен:\n"
        "  — быть привязан к ОДНОЙ из перечисленных выше компетенций (competency_id);\n"
        "  — иметь expected_level (0..5) — ожидаемый уровень владения для хорошего ответа;\n"
        "  — иметь краткий rationale — почему этот вопрос уместен в контексте профиля;\n"
        "  — быть открытым, провоцирующим рассуждение; не yes/no;\n"
        "  — содержать reference_answer — эталонный развёрнутый ответ для проверяющего "
        "(Markdown: перечень ключевых тезисов, которые должен упомянуть сотрудник уровня "
        "expected_level; при уместности — фрагменты кода в тройных backticks с указанием языка).\n\n"
        "Верни строго JSON (без обрамлений):\n"
        '{"questions": [{"competency_id": int, "question": str, '
        '"expected_level": int, "rationale": str, "reference_answer": str}]}'
    )
    return await _json_call(client, prompt, AIQuestionsResult)


