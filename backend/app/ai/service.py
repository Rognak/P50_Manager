async def _markdown_call(client: AsyncOpenAI, prompt: str) -> str:
    try:
        resp = await client.chat.completions.create(
            model=model_of(client),
            messages=[
                {"role": "system", "content": SYSTEM_MD},
                {"role": "user", "content": prompt},
            ],
            max_tokens=20000,
            temperature=0.6,
        )
    except OpenAIError as e:
        raise HTTPException(status_code=502, detail=f"Ошибка AI-провайдера: {e}")
    text = (resp.choices[0].message.content or "").strip()
    if text.startswith("```markdown"):
        text = text[len("```markdown") :].strip("`").strip()
    elif text.startswith("```"):
        text = text.strip("`").strip()
    return text


